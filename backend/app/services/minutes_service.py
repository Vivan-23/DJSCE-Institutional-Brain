"""
Formal meeting minutes, generated from an ingested meeting.

``build()`` assembles the record (attendees, summary, decisions, action items with
owners and due dates) from what extraction already stored; ``to_docx()`` and
``to_pdf()`` render it. Nothing is re-generated by the LLM at export time, so the
minutes match what reviewers saw in the app. Every document states that it was
machine-drafted and must be checked before circulation.
"""
import io
import json
from datetime import datetime, timezone
from typing import Any

from sqlmodel import Session, select

from app.core.institution_config import get_institution_config
from app.models.structured import Commitment, Employee, Meeting

_OPEN = ("open", "in_progress", "blocked")

DRAFT_NOTICE = (
    "Draft minutes generated automatically from the meeting transcript. Verify every "
    "decision and action item before circulating; this is not an approved record."
)


def _json_list(raw: str | None) -> list[str]:
    try:
        return [str(x) for x in json.loads(raw or "[]") if str(x).strip()]
    except (json.JSONDecodeError, TypeError):
        return []


class MinutesService:
    def build(self, db: Session, meeting: Meeting) -> dict[str, Any]:
        cfg = get_institution_config()
        names = {e.id: e.display_name for e in db.exec(select(Employee))}
        actions = [
            {
                "description": c.description,
                "owner": names.get(c.assignee_employee_id, "Unassigned"),
                "due": c.due_date.date().isoformat() if c.due_date else "Not set",
                "status": {"review": "done, awaiting confirmation", "done": "completed"}.get(
                    c.status, c.status.replace("_", " ")) + (f" ({c.progress}%)" if c.status in _OPEN and c.progress else ""),
            }
            for c in db.exec(
                select(Commitment).where(Commitment.source_meeting_id == meeting.id).order_by(Commitment.created_at)
            )
        ]
        dept = next((d.name for d in cfg.departments if d.code == meeting.department), None)
        return {
            "institution": cfg.full_name,
            "title": meeting.title,
            "date": meeting.occurred_at.date().isoformat(),
            "department": dept or "Institution-wide",
            "attendees": _json_list(meeting.participants),
            "summary": meeting.summary or "No summary was extracted for this meeting.",
            "decisions": _json_list(meeting.decisions),
            "actions": actions,
            "generated_at": datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC"),
            "notice": DRAFT_NOTICE,
        }

    @staticmethod
    def filename(minutes: dict[str, Any], ext: str) -> str:
        slug = "".join(ch if ch.isalnum() else "_" for ch in minutes["title"]).strip("_")[:60]
        return f"Minutes_{minutes['date']}_{slug}.{ext}"

    def to_docx(self, m: dict[str, Any]) -> bytes:
        from docx import Document
        from docx.shared import Pt

        doc = Document()
        doc.add_paragraph(m["institution"]).runs[0].bold = True
        doc.add_heading(f"Minutes: {m['title']}", level=1)
        doc.add_paragraph(f"Date: {m['date']}    Department: {m['department']}")
        notice = doc.add_paragraph(m["notice"])
        notice.runs[0].italic = True
        notice.runs[0].font.size = Pt(9)

        doc.add_heading("Attendees", level=2)
        doc.add_paragraph(", ".join(m["attendees"]) or "Not recorded")
        doc.add_heading("Summary", level=2)
        doc.add_paragraph(m["summary"])
        doc.add_heading("Decisions", level=2)
        for d in m["decisions"] or ["No decisions were recorded."]:
            doc.add_paragraph(d, style="List Number" if m["decisions"] else None)
        doc.add_heading("Action items", level=2)
        if m["actions"]:
            table = doc.add_table(rows=1, cols=4)
            table.style = "Table Grid"
            for cell, label in zip(table.rows[0].cells, ("Action", "Owner", "Due", "Status")):
                cell.text = label
                cell.paragraphs[0].runs[0].bold = True
            for a in m["actions"]:
                row = table.add_row().cells
                row[0].text, row[1].text, row[2].text, row[3].text = a["description"], a["owner"], a["due"], a["status"]
        else:
            doc.add_paragraph("No action items were recorded.")
        footer = doc.add_paragraph(f"Generated {m['generated_at']} by {get_institution_config().name}.")
        footer.runs[0].font.size = Pt(8)

        buf = io.BytesIO()
        doc.save(buf)
        return buf.getvalue()

    def to_pdf(self, m: dict[str, Any]) -> bytes:
        from xml.sax.saxutils import escape

        from reportlab.lib import colors
        from reportlab.lib.pagesizes import A4
        from reportlab.lib.styles import getSampleStyleSheet
        from reportlab.lib.units import cm
        from reportlab.platypus import ListFlowable, Paragraph, SimpleDocTemplate, Spacer, Table, TableStyle

        styles = getSampleStyleSheet()
        small = styles["BodyText"].clone("small", fontSize=8, leading=10, textColor=colors.grey)

        def p(text: str, style: str = "BodyText") -> Paragraph:
            return Paragraph(escape(text), styles[style] if isinstance(style, str) else style)

        story = [
            p(m["institution"], "Heading4"),
            p(f"Minutes: {m['title']}", "Title"),
            p(f"Date: {m['date']}    Department: {m['department']}"),
            Paragraph(f"<i>{escape(m['notice'])}</i>", small),
            Spacer(1, 0.4 * cm),
            p("Attendees", "Heading2"),
            p(", ".join(m["attendees"]) or "Not recorded"),
            p("Summary", "Heading2"),
            p(m["summary"]),
            p("Decisions", "Heading2"),
        ]
        if m["decisions"]:
            story.append(ListFlowable([p(d) for d in m["decisions"]], bulletType="1"))
        else:
            story.append(p("No decisions were recorded."))
        story.append(p("Action items", "Heading2"))
        if m["actions"]:
            cell = styles["BodyText"].clone("cell", fontSize=9, leading=11)
            rows = [[Paragraph(f"<b>{h}</b>", cell) for h in ("Action", "Owner", "Due", "Status")]]
            rows += [[Paragraph(escape(a[k]), cell) for k in ("description", "owner", "due", "status")] for a in m["actions"]]
            table = Table(rows, colWidths=[8.5 * cm, 3.5 * cm, 2.5 * cm, 2.5 * cm], repeatRows=1)
            table.setStyle(TableStyle([
                ("GRID", (0, 0), (-1, -1), 0.5, colors.grey),
                ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#e8eef7")),
                ("VALIGN", (0, 0), (-1, -1), "TOP"),
            ]))
            story.append(table)
        else:
            story.append(p("No action items were recorded."))
        story += [Spacer(1, 0.6 * cm), Paragraph(escape(f"Generated {m['generated_at']} by {get_institution_config().name}."), small)]

        buf = io.BytesIO()
        SimpleDocTemplate(buf, pagesize=A4, title=f"Minutes: {m['title']}", leftMargin=2 * cm, rightMargin=2 * cm,
                          topMargin=1.8 * cm, bottomMargin=1.8 * cm).build(story)
        return buf.getvalue()


minutes_service = MinutesService()
